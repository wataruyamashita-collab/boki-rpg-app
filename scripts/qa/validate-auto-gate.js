'use strict';
const assert=require('assert'),fs=require('fs'),path=require('path');
const core=require('./audit-core');
const root=path.resolve(__dirname,'../..');
const report=name=>JSON.parse(fs.readFileSync(path.join(root,'reports/auto-gate',name),'utf8'));
const final=report('final.json');
const rows=fs.readFileSync(path.join(root,'reports/auto-gate/question-review.jsonl'),'utf8').trim().split('\n').map(JSON.parse);
assert.strictEqual(rows.length,300);
assert.strictEqual(new Set(rows.map(row=>row.questionId)).size,300);
assert(rows.every(row=>row.requiredCheckIds.length>0&&row.requiredCheckIds.every(id=>row.executedCheckIds.includes(id))));
assert.deepStrictEqual(final.coverage,{TOTAL:300,DIRECTLY_TESTED:300,PASS:293,FAIL:7,MISSING:0,DUPLICATE:0});
assert.deepStrictEqual(final.gateImplementation,{unimplemented:0,requiredCheckNotExecuted:0,requiredLayerNotExecuted:0,checkCountZero:0});
assert.strictEqual(final.status,'FAIL','known production defects must remain RED in Phase A');
assert.strictEqual(final.productionModified,false);
assert.deepStrictEqual(final.mutations,{required:19,killed:19,survived:0,causalDeltaConfirmed:'19/19'});
assert.strictEqual(final.story.ROUTING_INTEGRATION,'TESTED');
assert.strictEqual(final.story.BROWSER_E2E,'UNVERIFIED');
assert.strictEqual(core.lockCheck().ok,true);
console.log('auto-gate state validator: ok (fail-closed evidence valid; known production defects remain RED)');
